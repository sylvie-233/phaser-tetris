/** 从 from 旋转到 to 时依次尝试的偏移 */
export function getKicks(type: TetrominoType, from: Rotation, to: Rotation): readonly Mino[] {
  const key = `${from}-${to}`;
  if (type === 'I') return I_KICKS[key];
  if (type === 'O') return O_KICKS[key];
  return JLSTZ_KICKS[key];
}
